# scripts/manifest_summary.py
"""Step 4d: write docs/manifest_summary.md — one review document for the whole claims manifest
(review gate before Step 5 evals). Reads only data/processed/claims_manifest.json; no numbers are typed here.
Usage: python scripts/manifest_summary.py"""
import json, os, sys

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
except Exception:
    pass
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = json.load(open(os.path.join(BASE, 'data', 'processed', 'claims_manifest.json'), encoding='utf-8'))
CH = {'reddit': 'Reddit', 'play_store': 'Play Store', 'tradingqna': 'TradingQnA', 'youtube': 'YouTube'}
PL = {'mostly_coin': 'Mostly Coin', 'coin_and_other_platforms': 'Coin and other platforms',
      'other_platforms_only': 'Other platforms only', 'platform_rarely_stated': 'Platform mostly not stated'}
ST = {'answered': 'Answered', 'partly_answered': 'Partly answered', 'not_answered': 'Not answered yet'}
cs, k = M['corpus_summary'], M['kpis']
N = cs['counted_N']
pct = lambda a, b: f'{round(100 * a / b)}%' if b else '–'
o = []
w = o.append

w('# Claims manifest summary (Step 4d review gate)\n')
w(f"_Generated by `scripts/manifest_summary.py` from `data/processed/claims_manifest.json` (built {cs['built_on']}). "
  'Every number below is computed; generated text is marked **(generated)**; quotes are exact user text._\n')
w('**Reading note:** these are public posts and reviews, which lean towards complaints. Counts are mentions, not a share of all '
  'users, and there is no retention percentage anywhere because there is no cohort or account data.\n')

w('## 1. Evidence base\n')
w(f"- **{cs['collected_unique']:,} unique posts** collected from {cs['channels']} channels; {cs['relevance_checked']:,} checked for relevance "
  f"(direct {cs['relevance_counts']['direct']}, indirect {cs['relevance_counts']['indirect']}, off-topic {cs['relevance_counts']['off_topic']}).")
w(f"- **Counted base: {N} posts** — direct, first-hand experience, unique ({cs['direct_hypothetical_excluded']} hypothetical posts excluded).")
w('- By channel: ' + ' · '.join(f"{CH[c]} {v} ({pct(v, N)})" for c, v in cs['channel_split'].items()))
p = cs['platform_split']
w(f"- By platform: Coin {p['coin']} · other platforms {p['other']} · not identifiable {p['not_identifiable']} (left blank, never guessed)")
w(f"- Dated posts: {cs['date_range']['dated_posts']} of {N}, {cs['date_range']['first']} to {cs['date_range']['last']} · recency " +
  ', '.join(f'{a} {b}' for a, b in cs['recency_mix'].items()))
w(f"- Human-confirmed posts (gold set + review round): {cs['human_confirmed_posts']}\n")

w('## 2. Headline numbers\n')
sd = k['stated_dropoff']
w('| Measure | Value | Note |')
w('| :-- | :-- | :-- |')
w(f"| Stated drop-off (SIP or platform) | {sd['count_investor']} of {sd['denominator']} ({pct(sd['count_investor'], sd['denominator'])}) | "
  f"SIP {sd['by_scope']['sip']}, platform {sd['by_scope']['platform']}; fund-level {sd['by_scope']['fund']} shown apart, not drop-off |")
w(f"| Leaving Coin vs leaving a competitor | {sd['platform_scope_coin']} vs {sd['platform_scope_competitor']} | platform-level posts only; "
  "reflects which apps' reviews were collected, so it is **not** a comparison of churn rates |")
mt = k['money_and_trust_breakers']
w(f"| Money and trust breakers | {mt['count']} of {mt['denominator']} ({pct(mt['count'], mt['denominator'])}) | money lost or held in {mt['money_incurred']} |")
ft = k['fix_type']
w(f"| What kind of fix (posts with a friction) | " + ', '.join(f'{a} {b}' for a, b in ft['counts'].items()) + f" | of {ft['denominator']}, from cause tags |")
ss = M['switch_summary']
w(f"| Stated switches | away from Coin {ss['from_coin']}, to Coin {ss['to_coin']} | {len(M['switch_flows'])} distinct from→to flows |\n")

w('## 3. Problems, by group and rank\n')
w('Rank = number of counted posts with the problem (a post can have several). Confidence: High = ≥5 posts, ≥2 channels, ≥3 human-confirmed.\n')
for gk, gname in M['groups'].items():
    ps = [x for x in M['problems'] if x['group'] == gk]
    if not ps:
        continue
    w(f'### {gname}\n')
    for x in ps:
        sdx = x['stated_dropoff']
        flag = f" · ⚑ {CH[x['top_channel']]} {pct(x['top_channel_share'] * 100, 100)} of posts" if x['channel_flag'] else ''
        w(f"**#{x['rank']} {x['id']} — {x['name']}**  ")
        w(f"{x['count']} of {N} posts · {x['confidence']} confidence · {PL[x['platform_label']]} "
          f"(Coin {x['platform_split']['coin']} / other {x['platform_split']['other']} / not stated {x['platform_split']['not_identifiable']}) · "
          f"drop-off {sdx['investor']} (leaving Coin {sdx['leaving_coin']}, competitor {sdx['leaving_competitor']}) · money {x['money']['count']}{flag}\n")
        w(f"(generated) {x['narrative']['statement']}\n")
        if x['quotes']:
            q = x['quotes'][0]
            meta = M['quotes_index'][q['id']]
            w(f"> {q['text']}\n>\n> — {meta['author_label']}, {meta['date'] or meta['recency']}" + (' (excerpt)' if q['excerpt'] else '') + '\n')
        w(f"_Would prove it wrong:_ {x['narrative']['invalidation']}\n")

w('## 4. The 9 discovery questions\n')
w('| Q | Question | Status | Evidence |')
w('| :-- | :-- | :-- | --: |')
for q in M['questions']:
    w(f"| {q['id']} | {q['question']} | {ST[q['status']]} | {q['evidence_count']} |")
w('')
for q in M['questions']:
    w(f"**{q['id']} — {ST[q['status']]}.** " + (f"(generated) {q['summary']['text']} " if q['summary'] else '') +
      (f"_Lowered from {ST[q['status_by_count']]}: {q['status_cap_reason']}_ " if q['status'] != q['status_by_count'] else '') +
      (f"_Missing:_ {q['gap_note']} " if q['gap_note'] else '') + (f"→ `{q['research_link']}`" if q['research_link'] else '') + '\n')

w('## 5. Next research tracks\n')
w('| Track | From | Evidence | Objective |')
w('| :-- | :-- | --: | :-- |')
for t in M['research_tracks']:
    w(f"| `{t['id']}` | {t['source']} | {t['evidence_count']} | {t['objective']} |")
w('')

w('## 6. How this was built and checked\n')
w('- Tags: in-session reading with an exact evidence span per tag; human gold set and a 40-record review round applied; gold labels override AI tags.')
w('- Problems: friction labels grouped into problems (`theme_map.json`); every label used maps to exactly one problem.')
w('- Build checks (all passed, or nothing is written): counts recomputed independently; channel and platform splits sum to the count; '
  'every quote is an exact substring of the raw record and contains its evidence span; generated text cites ≥3 posts from its own '
  'evidence, contains no digits, % or quotation marks; question status lowered only with a reason; interview questions are episodic; '
  'problem cards and research tracks share the same invalidation text.')
w('- Bias controls: denominators and channel split on every count; hypothetical and off-topic posts excluded; fund-level stops not counted '
  'as drop-off; leaving a competitor never counted as leaving Coin; quotes stating drop-off or money capped at their share of posts; '
  'forum-collected posts not counted as an answer to where investors go for help.')
w('- Privacy: posts where the author states their own name are never quoted; authors shown only as channel labels.\n')
w('**Caveats:** Play Store reviews lean negative; several problems draw over 70% of posts from one channel (flagged ⚑); '
  'many posts name no platform; three Play reviews filed under Coin are Kite app reviews and are counted as Kite.\n')
w('## 7. Open for Step 5 (evals)\n')
w('Score the manifest against the `docs/evals.md` §17 rubric (hallucination 40 · bias 30 · consistency 30), including the human-reviewed '
  'off-topic leakage sample and the agreement metrics; then the UI (Step 6) reads only this manifest.')
out = os.path.join(BASE, 'docs', 'manifest_summary.md')
open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
print('written', out)
